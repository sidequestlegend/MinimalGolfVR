// Writes src/levels.json from the level table in ../PORT.md (section 5.3, parsed there from the upstream scene
// Assets/MinimalGolf/Scenes/MinimalGolf.unity) and the authored level slots of section 5.1.
//
//   node tools/levels-from-port.ts            writes src/levels.json
//   node tools/levels-from-port.ts --check    exits 1 when src/levels.json differs from what PORT.md gives
//
// Upstream has no level data file: the levels exist only as scene objects (PORT.md 5.3). This table is the part of
// them the rules need: name, par, course bounds, ball reset point, hole centre, reveal part count, authored slot.

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { argv, exit } from "node:process";
import { fileURLToPath } from "node:url";

export interface LevelData {
  /** 0-based index in play order (upstream `levels` array, SCENE:2061). */
  index: number;
  levelName: string;
  par: number;
  /** Local units (the level root's space; the course is scaled by the table scale, 0.05). */
  courseWidth: number;
  courseLength: number;
  /** "Ball Reset Point", level-local. */
  ballSpawn: [number, number, number];
  /** "Hole Center - Cup Assist Target", level-local. */
  holeCenter: [number, number, number];
  /** `animatedParts.Length` of the level's LevelRevealAnimator (an empty entry still counts, PORT.md A9). */
  revealParts: number;
  /** The level root's authored local position under VRCourseLevels (its layout slot). */
  slot: [number, number, number];
  /** True where PORT.md marks a value as computed and still to be confirmed in the editor. */
  provisional?: boolean;
}

const here = (path: string) => fileURLToPath(new URL(path, import.meta.url));

function triple(text: string): [number, number, number] {
  const m = /\(\s*(-?[\d.]+)\s*,\s*(-?[\d.]+)\s*,\s*(-?[\d.]+)\s*\)/.exec(text);
  if (!m) throw new Error(`no (x, y, z) in '${text}'`);
  return [Number(m[1]), Number(m[2]), Number(m[3])];
}

export function levelsFromPort(port: string): LevelData[] {
  const lines = port.split(/\r?\n/);
  const start = lines.findIndex((l) => l.startsWith("### 5.3 Levels"));
  if (start < 0) throw new Error("PORT.md has no '### 5.3 Levels' section");
  const rows: LevelData[] = [];
  for (let i = start + 1; i < lines.length && !lines[i]!.startsWith("### "); i++) {
    const line = lines[i]!;
    const m = /^\| (\d) ([A-Z ]+?) \| (\d+) \| ([\d.]+) x ([\d.]+)[^|]*\| [^|]*\| ([^|]+)\| ([^|]+)\| (\d+) \|/.exec(line);
    if (!m) continue;
    const hole = m[7]!;
    const row: LevelData = {
      index: Number(m[1]) - 1,
      levelName: m[2]!.trim(),
      par: Number(m[3]),
      courseWidth: Number(m[4]),
      courseLength: Number(m[5]),
      ballSpawn: triple(m[6]!),
      holeCenter: triple(hole),
      revealParts: Number(m[8]),
      slot: [0, 0, 0],
    };
    if (/\babout\b|to be confirmed/i.test(hole)) row.provisional = true;
    rows.push(row);
  }
  if (rows.length !== 8) throw new Error(`expected 8 level rows in PORT.md 5.3, found ${rows.length}`);
  // Section 5.1: "Level 2 ... Level 8       same five groups, at (10,0,19) (-10,0,19) ..." (level 1 is at (0,0,0)).
  const slotLine = lines.find((l) => /Level 2 \.\.\. Level 8 .*same five groups, at/.test(l));
  if (!slotLine) throw new Error("PORT.md 5.1 has no line with the slots of levels 2 to 8");
  const slots = [...slotLine.matchAll(/\((-?[\d.]+),(-?[\d.]+),(-?[\d.]+)\)/g)].map((s) => [Number(s[1]), Number(s[2]), Number(s[3])] as [number, number, number]);
  if (slots.length !== 7) throw new Error(`expected 7 slots for levels 2 to 8, found ${slots.length}`);
  slots.forEach((s, k) => (rows[k + 1]!.slot = s));
  return rows;
}

export function levelsJson(port: string): string {
  const note = "Generated by tools/levels-from-port.ts from PORT.md 5.3 and 5.1 (the upstream scene). Do not edit.";
  return JSON.stringify({ note, levels: levelsFromPort(port) }, null, 2) + "\n";
}

if (argv[1] && resolve(argv[1]) === fileURLToPath(import.meta.url)) {
  const text = levelsJson(readFileSync(here("../../PORT.md"), "utf8"));
  const target = here("../src/levels.json");
  if (argv.includes("--check")) {
    const now = readFileSync(target, "utf8").replace(/\r\n/g, "\n");
    if (now !== text) {
      console.error("src/levels.json differs from PORT.md: run npm run levels");
      exit(1);
    }
    console.log("src/levels.json matches PORT.md");
  } else {
    writeFileSync(target, text);
    console.log(`wrote ${target}`);
  }
}
